#include <iostream>
#include <string>
#include <sstream>
#include <fstream>
#include <vector>
#include <algorithm>
#include <cctype>
#include <cstdlib>

#ifndef SPARC_2_CPP
#define SPARC_2_CPP

namespace sp
{
	class PState;
	class Action;
	class Transition;
	class DomainSort;

	/**
	 * \brief This method executes the shell command that is passed as input parameter.
	 * \param cmd String to be executed in console.
	 * \return Returns the text generated by the OS as result of executing the command held in cmd.
	*/
	std::string shellCmd(std::string cmd);

	/**
	 * \brief This method is for checking if a string ends with a given sub-string.
	 * \param fullString The whole string.
	 * \param ending The sub-string to be checked on the whole string.
	 * \return Returns true if fullString ends with ending, otherwise, false.
	*/
	bool endsWith(std::string const &fullString,std::string const &ending);

	/**
	 * \brief This method is for checking if a string starts with a given sub-string.
	 * \param fullString The whole string.
	 * \param start The sub-string to be checked on the whole string.
	 * \return Returns true if fullString starts with start, otherwise, false.
	*/
	bool startsWith(std::string const &fullString, std::string const &start);

	/**
	 * \brief This method extracts from an input string a sub-string located between two indexes. The characters from the the input string that correspnd to the limiting indexes are not part of the sub-string.
	 * \param fullString Input string from which the sub-string will be extracted.
	 * \param leftLimit Index at that bounds the sub-string from the left.
	 * \param rightLimit Index at that bounds the sub-string from the right.
	 * \return Returns the sub-string located between the leftLimit and rightLimit indexes within fullString.
	*/
	std::string strBtwn(std::string const &fullString, int leftLimit, int rightLimit);

	/**
	 * \brief This method counts the amount of occurrences of the string s within string fullString. If the string s has a length greater than 1 and its occurrences overlap, these are considered in the counting process. For instance, a call like countOcc("asasa","asa") would return 2.
	 * \param fullString The string from which the method will seek for occurrences.
	 * \param s The string whose occurrences in fullString will be counted.
	 * \return Returns the amount of times string s appears in fullString.
	*/
	int countOcc(std::string const &fullString, std::string const &s);

	/**
	 * \brief This method corrects the input vector by concatenating continuous elements of the vector that when are joint, are enclosed by the most outer parenthesis.
	 * \param commaSplit Vector of strings to be corrected.
	 * \return Returns a vector of strings, where each string either contains both oppening and closing parenthesis, or none of them.
	*/
	std::vector<std::string> correctCommaSplit(std::vector<std::string> commaSplit);

	/**
	 * \brief This method eliminates the occurrences of character ' ', i.e. the space character.
	 * \param s String to be modified.
	 * \return Returns the version without spaces of the input string s.
	*/
	std::string stripSpaces(std::string const &s);

	/**
	 * \brief This method eliminates the occurrences of the special character '\t', i.e. the tab character.
	 * \param s String to be modified.
	 * \return Returns the version without tab spaces of the input string s.
	*/
	std::string stripTabs(std::string const &s);

	/**
	 * \brief This method is for segmenting an input string into a list of tokens separated by a delimiter sub-string.
	 * \param fullString The whole input string.
	 * \param delimiter The sub-string that will be considered the token delimiter.
	 * \return Returns a vector of tokens separated by the delimiter string.
	*/
	std::vector<std::string> splitStr(std::string const &fullString,std::string const &delimiter);

	/**
	 * \brief This method is for verifying if a string could be succesfully converted into an integer number.
	 * \param inputString The string to be verified.
	 * \return Returns true if inputString can be successfully converted into an integer number, otherwise, false.
	*/
	bool isInt(std::string const &inputString);

	/**
	 * \brief This method is for verifying if a string could be succesfully converted into a float number.
	 * \param inputString The string to be verified.
	 * \return Returns true if inputString can be successfully converted into a float number, otherwise, false.
	*/
	bool isFloat(std::string const &inputString);

	/**
	 * \brief This method extracts from a text file a set of answer sets, where each answer set is constituted by a collection of literals, therefore each answer set is represented by a PState object. 
	 * \param answerSetsFile String containing the path to the answer sets file.
	 * \return Returns a vector of PState objects, from which each one corresponds to an answer set.
	*/
	std::vector<PState> pstatesFromFile(std::string const &answerSetsFile);

	/**
	 * \brief This method verifies if the string input is an element of the sort with index sortToCheck within the DomainSort object ds, or if it is an element of one of its sub-sorts.
	 * \param ds DomainSort object whose sub-sort hierarchy will be used to perform to determine if input belongs to the sort that corresponds to index sortToCheck.
	 * \param input String that will be seeked within the sub-sort hierarchy.
	 * \param sortToCheck Sort index corresponding to the sort from where the search will start and go downwards through the hierarchy.
	 * \return Returns true if input is found to be a sub-sort of the sort with index sortToCheck, otherwise, false.
	*/
	bool recursiveCheck(DomainSort const &ds, std::string const &input, int sortToCheck);

	/**
	 * \brief This method verifies if the literal in the string input satisfies the string definition def, with respect the sort hierarchy in ds. a literal is said to satisfy a definition if all of the definition components are satisfied by their corresponding component in the literal. There 3 type of definition components: "X" is satisfied by any non-empty string. A component that starts with #, e.g. "#animal", is satisfied by a string that is a sub-sort element in ds. The third type of definition component is a string that does not start with # and is different than "X", and can only be satisfied by itself, i.e., a definition component "dog" can only be satisfied by the string "dog". For instance, the definition "#action(johnny,X)" is satisfied by "go(johnny,school)", with respect a DomainSort where "go" is an element of sort "#action" or element of one of the sub-sorts of "#action".
	 * \param ds DomainSort used to solve those definitions that start with #.
	 * \param def The definition string.
	 * \param input The string to be evaluated.
	 * \return Returns true if the string input satisfies the string definition def.
	*/
	bool checkDef(DomainSort const &ds, std::string const &def, std::string const &input);

	/**
	 * \brief This method extracts from an input state (ps) a sub-set of its literals based on a collection of definitions (defs) with respect a the DomianSort (ds). The sub-set of literals is constituted by those that satisfy at least one of the definitions in defs.
	 * \param ds DomainSort used to solve those definitions that start with #.
	 * \param ps PState object from which the new sub-set of literals will be extracted.
	 * \param defs Vector of definitions.
	 * \return Returns a set of literals in the form of a PState object.
	*/
	PState subPstate(DomainSort const &ds, PState const &ps, std::vector<std::string> const &defs);

}

#endif
